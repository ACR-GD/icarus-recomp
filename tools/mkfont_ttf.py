#!/usr/bin/env python3
"""Rasterize the replacement dialogue font into runtime/font_text.h.

usage: mkfont_ttf.py FONT.ttf [size] [variation]   (default: Crimson Pro, 16 px, SemiBold)

The game draws text one 8x16 glyph at a time with its baseline at row 11 of the cell; glyphs here
keep that baseline so text sits where the game's layout expects it. Alpha is stored as 8-bit
coverage; the runtime blends it into the 8-bit screen through the current palette.
Font: Crimson Pro (c) The Crimson Pro Project Authors, SIL Open Font License 1.1 (tools/fonts/).
Get it from https://github.com/google/fonts/tree/main/ofl/crimsonpro
"""
import sys
from PIL import Image, ImageDraw, ImageFont
path = sys.argv[1]
size = int(sys.argv[2]) if len(sys.argv) > 2 else 16
var = (sys.argv[3] if len(sys.argv) > 3 else 'SemiBold').encode()
font = ImageFont.truetype(path, size)
try: font.set_variation_by_name(var)
except Exception: pass
BASELINE = 11
ascent = font.getmetrics()[0]
glyphs = []
for c in range(32, 256):
    ch = bytes([c]).decode('cp1252', 'replace')
    adv = font.getlength(ch)
    im = Image.new('L', (40, 40), 0)
    ImageDraw.Draw(im).text((8, 8 + BASELINE - ascent), ch, font=font, fill=255)
    bb = im.getbbox()
    if not bb or ch == '�': glyphs.append((round(adv), 0, 0, 0, 0, b'')); continue
    x0, y0, x1, y1 = bb
    data = bytes(im.crop(bb).tobytes())
    glyphs.append((round(adv), x0 - 8, y0 - 8, x1 - x0, y1 - y0, data))
with open('runtime/font_text.h', 'w') as o:
    o.write('// generated by tools/mkfont_ttf.py from %s, %d px. Crimson Pro: SIL Open Font License 1.1.\n' % (path.split('/')[-1], size))
    o.write('struct tglyph { uint8_t adv; int8_t x, y; uint8_t w, h; uint32_t off; };\n')
    o.write('static const struct tglyph TGLYPH[224] = {\n')
    off = 0
    for g in glyphs:
        o.write('  {%d, %d, %d, %d, %d, %d},\n' % (g[0], g[1], g[2], g[3], g[4], off)); off += len(g[5])
    o.write('};\nstatic const uint8_t TALPHA[%d] = {\n' % max(off, 1))
    blob = b''.join(g[5] for g in glyphs) or b'\0'
    for k in range(0, len(blob), 32): o.write('  ' + ','.join(str(b) for b in blob[k:k + 32]) + ',\n')
    o.write('};\n')
print('glyphs', len(glyphs), 'alpha bytes', off)
