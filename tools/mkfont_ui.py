#!/usr/bin/env python3
"""Rasterize the launcher fonts into runtime/font_ui.h (ASCII, 8-bit coverage, 2x UI scale).

usage: mkfont_ui.py CrimsonPro[wght].ttf CrimsonPro-Italic[wght].ttf
Font: Crimson Pro (c) The Crimson Pro Project Authors, SIL Open Font License 1.1 (tools/fonts/).
"""
import sys
from PIL import Image, ImageDraw, ImageFont
path, ipath = sys.argv[1], sys.argv[2]
FONTS = [('UI_BODY', 30, b'Medium'), ('UI_SMALL', 25, b'Medium'), ('UI_HEAD', 36, b'SemiBold'),
         ('UI_TITLE', 84, b'Bold'), ('UI_SUB', 32, b'Medium Italic')]
out = ['// generated by tools/mkfont_ui.py from Crimson Pro (SIL Open Font License 1.1)',
       'struct uiglyph { uint8_t adv, w, h; int8_t x, y; uint32_t off; };',
       'struct uifont { int size, ascent, descent; const struct uiglyph *g; const uint8_t *a; };']
for name, size, var in FONTS:
    f = ImageFont.truetype(ipath if b'Italic' in var else path, size)
    try: f.set_variation_by_name(var)
    except Exception as e: print('variation', var, e)
    asc, desc = f.getmetrics()
    gl, blob = [], bytearray()
    for c in range(32, 127):
        im = Image.new('L', (size * 3, size * 3), 0)
        ImageDraw.Draw(im).text((size, size + asc), chr(c), font=f, fill=255, anchor='ls')
        bb = im.getbbox(); adv = round(f.getlength(chr(c)))
        if not bb: gl.append((adv, 0, 0, 0, 0, len(blob))); continue
        x0, y0, x1, y1 = bb
        gl.append((adv, x1 - x0, y1 - y0, x0 - size, y0 - size, len(blob)))
        blob += im.crop(bb).tobytes()
    out.append('static const struct uiglyph %s_G[95] = {%s};' % (name, ','.join('{%d,%d,%d,%d,%d,%d}' % g for g in gl)))
    out.append('static const uint8_t %s_A[%d] = {' % (name, len(blob)))
    for k in range(0, len(blob), 40): out.append(','.join(str(b) for b in blob[k:k + 40]) + ',')
    out.append('};')
    out.append('static const struct uifont %s = {%d, %d, %d, %s_G, %s_A};' % (name, size, asc, desc, name, name))
open('runtime/font_ui.h', 'w').write('\n'.join(out) + '\n')
print('ok', sum(1 for l in out))
