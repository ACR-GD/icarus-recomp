"""Generate runtime/font6x8.h from Pillow's built-in bitmap font (X11-derived, permissive)."""
from PIL import Image, ImageDraw, ImageFont
f = ImageFont.load_default_imagefont()
rows = []
for c in range(32, 127):
    im = Image.new('1', (12, 14), 0); d = ImageDraw.Draw(im); d.text((0, 0), chr(c), font=f, fill=1)
    bb = im.getbbox()
    g = []
    for y in range(3, 11):    # 8 rows: cap height to descender
        v = 0
        for x in range(6): v = (v << 1) | (1 if im.getpixel((x, y)) else 0)
        g.append(v)
    rows.append(g)
with open('runtime/font6x8.h', 'w') as o:
    o.write('// generated by tools/mkfont.py\nstatic const uint8_t FONT6X8[95][8] = {\n')
    for c, g in zip(range(32, 127), rows): o.write('  {%s}, // %r\n' % (','.join('0x%02x' % v for v in g), chr(c)))
    o.write('};\n')
# preview
for c in 'Ag':
    g = rows[ord(c) - 32]
    print('\n'.join(format(v, "06b").replace('0', '.').replace('1', '#') for v in g)); print()
